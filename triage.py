# A label and its value are often on separate lines ("PATIENT DETAILS" above
# "FIRSTNAME A LASTNAME"), so the label match stops at the end of its own line and
# the following line is inspected separately. Using \s here instead of [ \t]
# ran the match across the newline and swallowed the label as if it were a
# name - which is how "Lastname" survived a scrub that removed "Firstname A".
# Must be a *field label*, not the word. Matching bare "patient" anywhere hit
# ordinary prose - "The patient presented with...", "Patient was located At
# home" - and took the following capitalised words as a name, learning "Video"
# and "Living Condition" as patient names and substituting them into summaries.
# So: start of line, and either a colon or an all-caps header.
PATIENT_LABEL_RX = re.compile(
    r"^[ \t]*(?:patient(?:[ \t]+(?:name|details|information))?[ \t]*:"
    r"|PATIENT[ \t]+(?:DETAILS|NAME|INFORMATION)[ \t]*$)", re.I)
NAME_TOKENS_RX = re.compile(
    r"([A-Z][A-Za-z.'\-]{1,}(?:(?:,[ \t]*|[ \t]+)[A-Z][A-Za-z.'\-]*){1,3})")

NAME_STOPWORDS = {
    "name", "names", "patient", "details", "detail", "information", "info",
    "date", "birth", "sex", "male", "female", "the", "and", "for", "ids", "id",
    "record", "number", "account", "dob", "age", "phone", "address", "mrn",
    "summary", "visit", "results", "report", "lab", "labs", "test", "tests",
    "case", "unit", "location", "provider", "client", "deliver", "consulting",
}


def _name_parts(raw):
    parts = [w.strip(" .,") for w in re.split(r"[,\s]+", raw)]
    return [w for w in parts if len(w) > 2 and w.lower() not in NAME_STOPWORDS]


def patient_names(text, extra=()):
    """Name fragments belonging to the patient, for scrubbing model output.

    `extra` comes from config.json ("patient_names"). That list is the reliable
    half: the patient is the same person in every document, whereas per-document
    detection depends on however this particular portal lays out its header.
    Detection stays as a backstop for documents naming someone the list misses.

    The prompt already forbids putting a patient name in a field; qwen did it
    anyway in 2 of 28 documents. An instruction is not a control.
    """
    names = set()
    for n in extra or ():
        names.update(_name_parts(n))
        names.add(n.strip())

    lines = text[:6000].splitlines()
    for i, line in enumerate(lines):
        m = PATIENT_LABEL_RX.search(line)
        if not m:
            continue
        # Stop at the column break, or the capture runs on into the next field
        # ("Patient Name: Lastname, Firstname A     Case #: X-00-0000000" taught it
        # that "Case" was part of the name).
        rest = re.split(r"\s{3,}", line[m.end():].strip())[0]
        cand = NAME_TOKENS_RX.match(rest)
        if not cand:                       # value wrapped to the following line
            for probe in lines[i + 1:i + 3]:
                if probe.strip():
                    cand = NAME_TOKENS_RX.match(
                        re.split(r"\s{3,}", probe.strip())[0])
                    break
        if cand:
            parts = _name_parts(cand.group(1))
            if parts:
                names.update(parts)
                names.add(" ".join(parts))
    return {n for n in names if n and n.lower() not in NAME_STOPWORDS}


def scrub_identifiers(fields, text, extra=()):
    """Strip patient identifiers out of the model's free-text fields.

    A title drops the name outright - "Lab Results for Firstname A Lastname"
    becomes "Lab Results". A summary keeps its grammar by substituting "the
    patient", since the sentence is usually about them. Middle initials adjacent
    to a removed name go too, or the field keeps a stray capital letter.

    Returns the list of fields that were changed.
    """
    names = sorted(patient_names(text, extra), key=len, reverse=True)
    if not names:
        return []
    alts = "|".join(re.escape(n) for n in names)
    # One match must swallow the whole name, however it is written: "Lastname,
    # Firstname A" is three tokens, and matching them separately yields "the
    # patient, the patient". After the first part, keep consuming further name
    # parts and bare initials.
    name_rx = re.compile(
        r"\b(?:" + alts + r")\b(?:[\s,]+(?:(?:" + alts + r")\b|[A-Z]\.?(?![a-z])))*",
        re.I)

    changed = []
    for key in ("title", "summary"):
        val = fields.get(key)
        if not val or not name_rx.search(val):
            continue
        if key == "title":
            out = name_rx.sub("", val)
            out = re.sub(r"\s*\b(?:for|of|to|by)\s*$", "", out.strip(), flags=re.I)
        else:
            out = name_rx.sub("the patient", val)
            out = re.sub(r"(?:\bthe patient\b[\s,]*){2,}", "the patient ", out,
                         flags=re.I)
        out = re.sub(r"\s{2,}", " ", out).strip(" -,:;")
        if out:
            out = out[0].upper() + out[1:]
        fields[key] = out or None
        changed.append(key)
    return changed


def http_json(path, payload, timeout=900):
    req = urllib.request.Request(
        HOST + path, data=json.dumps(payload).encode(),
        headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


class Working:
    """Spinner for the slow call. Prefill dominates; expect 30-90s a document."""

    def __init__(self, label):
        self.label, self.stop, self.t0 = label, threading.Event(), time.monotonic()

    def __enter__(self):
        if sys.stderr.isatty():
            threading.Thread(target=self._spin, daemon=True).start()
        return self

    def _spin(self):
        frames = "|/-\\"
        i = 0
        while not self.stop.is_set():
            sys.stderr.write(
                f"\r  {frames[i % 4]} {self.label} {time.monotonic() - self.t0:4.0f}s")
            sys.stderr.flush()
            i += 1
            self.stop.wait(0.25)

    def __exit__(self, *exc):
        self.stop.set()
        if sys.stderr.isatty():
            sys.stderr.write("\r" + " " * 60 + "\r")
            sys.stderr.flush()


def describe(text, model):
    """Ask the model for title / doc_type / specialty / summary."""
    body = text[:MODEL_CHARS]
    if len(text) > MODEL_CHARS:
        body += "\n[document truncated for length]"
    payload = {
        "model": model,
        "prompt": PROMPT.format(doc_types=", ".join(DOC_TYPES),
                                specialties=", ".join(SPECIALTIES), body=body),
        "stream": False,
        "think": THINK,
        "format": "json",
        "options": {"temperature": 0, "seed": 42,
                    "num_ctx": NUM_CTX, "num_predict": NUM_PREDICT},
    }
    with Working("qwen is reading the document"):
        r = http_json("/api/generate", payload)
    raw = (r.get("response") or "").strip()
    if "</think>" in raw:                        # belt and braces alongside think=False
        raw = raw.split("</think>", 1)[1].strip()
    try:
        out = json.loads(raw)
    except ValueError:
        m = re.search(r"\{.*\}", raw, re.S)
        if not m:
            return None, f"model returned no JSON: {raw[:160]}"
        try:
            out = json.loads(m.group(0))
        except ValueError as e:
            return None, f"model JSON did not parse: {e}"

    clean = {}
    for k in ("title", "doc_type", "specialty", "summary"):
        v = out.get(k)
        clean[k] = v.strip() if isinstance(v, str) and v.strip() else None
    if clean["doc_type"] and clean["doc_type"].lower() not in DOC_TYPES:
        clean["doc_type"] = "other"
    if clean["specialty"] and clean["specialty"].lower() not in SPECIALTIES:
        clean["specialty"] = "other"
    return clean, None


