STATUS_MARK = {
    "described": "+", "described_ambiguous": "?", "extracted": "+",
    "not_clinical": "-", "too_short": "-", "needs_ocr": "!",
    "describe_failed": "!",
}


def show(prop, verbose):
    mark = STATUS_MARK.get(prop["status"], " ")
    print(f"\n  {mark} {prop['source_file']}  [{prop['status']}]")
    c = prop.get("classification")
    if c:
        print(f"      {c['verdict']}: {c.get('reason','')}")
        if verbose:
            a = "  ".join(f"{k}={v}" for k, v in c["anchors"].items())
            v = "  ".join(f"{k}={n}" for k, n in c["vetoes"].items() if n)
            print(f"          anchors  {a}   ({c['chars']} chars)")
            if v:
                print(f"          vetoes   {v}")
    if prop.get("note"):
        print(f"      note: {prop['note']}")
    for k in ("date", "title", "doc_type", "specialty", "provider", "facility",
              "summary"):
        if k in prop["fields"]:
            v = prop["fields"][k]
            src = prop["field_sources"].get(k) or "not found"
            shown = v if v is not None else "--"
            if isinstance(shown, str) and len(shown) > 66:
                shown = shown[:63] + "..."
            print(f"      {k:<10} {shown}")
            if verbose or v is None:
                print(f"      {'':<10}   via {src}")


def report():
    files = sorted(f for f in os.listdir(QUEUE_DIR) if f.endswith(".json")) \
        if os.path.isdir(QUEUE_DIR) else []
    if not files:
        print("Queue is empty.")
        return
    print(f"{len(files)} proposal(s) in {QUEUE_DIR}\n")
    for fn in files:
        with open(os.path.join(QUEUE_DIR, fn)) as f:
            p = json.load(f)
        title = p["fields"].get("title") or p["source_file"]
        date = p["fields"].get("date") or "??????????"
        print(f"  {STATUS_MARK.get(p['status'],' ')} {date}  {title[:56]:<56} "
              f"{p['status']}")


def main():
    ap = argparse.ArgumentParser(
        description="Triage clinical PDFs out of the Taildrop inbox.")
    ap.add_argument("--inbox", default=DEFAULT_INBOX,
                    help=f"directory to scan (default {DEFAULT_INBOX})")
    ap.add_argument("--model", default=MODEL, help=f"Ollama model (default {MODEL})")
    ap.add_argument("--dry-run", action="store_true",
                    help="classify and extract, but never call the model")
    ap.add_argument("--force", action="store_true",
                    help="re-triage documents already in the manifest")
    ap.add_argument("--limit", type=int, help="stop after N new documents")
    ap.add_argument("--report", action="store_true", help="list the queue and exit")
    ap.add_argument("--refresh-roster", action="store_true",
                    help="re-fetch the clinician roster from the server first")
    ap.add_argument("--reextract", action="store_true",
                    help="recompute date/provider/facility for queued proposals, "
                         "leaving the model's fields alone")
    ap.add_argument("-v", "--verbose", action="store_true",
                    help="show classifier evidence and every field's provenance")
    a = ap.parse_args()

    if a.report:
        report()
        return

    global ROSTER
    if a.refresh_roster:
        try:
            with open(os.path.join(HERE, "config.json")) as f:
                cfg = json.load(f)
            ROSTER = fetch_roster(cfg)
            print(f"roster: fetched {len(ROSTER)} clinicians")
        except (OSError, ValueError, urllib.error.URLError) as e:
            sys.exit(f"Could not fetch the roster: {e}")
    else:
        ROSTER = load_roster()
        if ROSTER:
            print(f"roster: {len(ROSTER)} clinicians (cached; "
                  f"--refresh-roster to update)")

    try:
        acquire_lock()
    except Busy as e:
        sys.exit(str(e))

    try:
        _run(a)
    finally:
        release_lock()


def _run(a):
    if a.reextract:
        reextract()
        return

    if not os.path.isdir(a.inbox):
        sys.exit(f"No such directory: {a.inbox}")

    if not a.dry_run:
        try:
            urllib.request.urlopen(HOST + "/api/tags", timeout=10).read()
        except (urllib.error.URLError, OSError) as e:
            sys.exit(f"Cannot reach Ollama at {HOST} ({e}).\n"
                     f"Start it with:  ollama serve\n"
                     f"Or classify without a model:  {sys.argv[0]} --dry-run")

    pdfs = sorted(os.path.join(a.inbox, f) for f in os.listdir(a.inbox)
                  if f.lower().endswith(".pdf"))
    if not pdfs:
        print(f"No PDFs in {a.inbox}")
        return

    manifest = load_manifest()
    print(f"clinic-triage  ·  {len(pdfs)} PDF(s) in {a.inbox}"
          f"{'  ·  dry run' if a.dry_run else '  ·  model ' + a.model}")

    seen = new = 0
    for path in pdfs:
        digest = sha256_file(path)
        if digest in manifest and not a.force:
            seen += 1
            continue
        if a.limit and new >= a.limit:
            break
        prop = triage_one(path, a.model, a.dry_run)
        show(prop, a.verbose)
        if prop["status"] not in ("not_clinical", "too_short"):
            write_proposal(prop)
        manifest[digest] = {
            "source_file": prop["source_file"], "first_seen": now(),
            "status": prop["status"],
        }
        new += 1

    save_manifest(manifest)
    print(f"\n{new} triaged, {seen} already in the manifest.")
    if new and not a.dry_run:
        print(f"Proposals in {QUEUE_DIR} — read them before stage 3 posts anything.")


if __name__ == "__main__":
    main()
