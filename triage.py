def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def extract_text(path):
    """Layout-preserving text. -layout is not cosmetic here: without it the
    header is linearised and 'Provider:' lands four lines from its value."""
    try:
        out = subprocess.run(["pdftotext", "-q", "-layout", path, "-"],
                             capture_output=True, timeout=60)
        text = out.stdout.decode("utf-8", "replace").strip()
        if text:
            return text
    except (OSError, subprocess.SubprocessError):
        pass
    return None


def load_manifest():
    if os.path.exists(MANIFEST):
        with open(MANIFEST) as f:
            return json.load(f)
    return {}


def save_manifest(m):
    os.makedirs(STATE_DIR, exist_ok=True)
    tmp = MANIFEST + ".tmp"
    with open(tmp, "w") as f:
        json.dump(m, f, indent=2, sort_keys=True)
    os.replace(tmp, MANIFEST)


def now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def triage_one(path, model, dry_run):
    """Run one document through the gates. Returns the proposal dict."""
    name = os.path.basename(path)
    digest = sha256_file(path)
    prop = {
        "sha256": digest, "source_file": name,
        "source_path": os.path.abspath(path),
        "bytes": os.path.getsize(path), "triaged_at": now(),
        "status": "pending", "fields": {}, "field_sources": {},
    }

    text = extract_text(path)
    if not text:
        prop["status"] = "needs_ocr"
        prop["note"] = "No text layer. Scanned PDF - needs OCR before it can be read."
        return prop

    verdict, detail = classify(text)
    prop["classification"] = dict(detail, verdict=verdict)
    if verdict in ("not_clinical", "too_short"):
        prop["status"] = verdict
        prop["note"] = detail.get("reason")
        return prop

    for key, fn in (("date", lambda t: extract_date(t, name)),
                    ("provider", extract_provider),
                    ("facility", extract_facility)):
        value, source = fn(text)
        prop["fields"][key] = value
        prop["field_sources"][key] = source

    apply_roster(prop["fields"], prop["field_sources"], text, name, ROSTER)

    if dry_run:
        prop["status"] = "extracted"
        prop["note"] = "--dry-run: model not called, no description proposed."
        return prop

    described, err = describe(text, model)
    if err:
        prop["status"] = "describe_failed"
        prop["note"] = err
        return prop
    prop["fields"].update(described)
    for k in described:
        prop["field_sources"][k] = f"model ({model})"
    for k in scrub_identifiers(prop["fields"], text, KNOWN_NAMES):
        prop["field_sources"][k] = f"model ({model}), patient name removed"
    prop["status"] = "described" if verdict == "clinical" else "described_ambiguous"
    return prop


def write_proposal(prop):
    os.makedirs(QUEUE_DIR, exist_ok=True)
    path = os.path.join(QUEUE_DIR, prop["sha256"][:16] + ".json")
    with open(path, "w") as f:
        json.dump(prop, f, indent=2)
    return path


LOCK = os.path.join(STATE_DIR, "triage.lock")


class Busy(Exception):
    pass


def acquire_lock():
    """One triage at a time. Two concurrent runs share a manifest and a queue
    directory, so the second silently overwrites the first's work - including
    replacing finished descriptions with un-described ones."""
    os.makedirs(STATE_DIR, exist_ok=True)
    if os.path.exists(LOCK):
        try:
            with open(LOCK) as f:
                pid = int(f.read().strip())
        except (ValueError, OSError):
            pid = None
        if pid:
            try:
                os.kill(pid, 0)
            except OSError:
                pass                      # stale lock, the process is gone
            else:
                raise Busy(f"another triage is running (pid {pid}). "
                           f"Wait for it, or remove {LOCK} if you are sure "
                           f"it is dead.")
    with open(LOCK, "w") as f:
        f.write(str(os.getpid()))


def release_lock():
    try:
        os.remove(LOCK)
    except OSError:
        pass


def reextract():
    """Recompute date / provider / facility for every queued proposal.

    The model's fields are expensive and are left exactly as they are; only the
    regex-derived ones are refreshed. Use after changing an extractor, instead
    of paying for another full describe run.
    """
    files = sorted(f for f in os.listdir(QUEUE_DIR)
                   if f.endswith(".json")) if os.path.isdir(QUEUE_DIR) else []
    if not files:
        print("Queue is empty.")
        return
    changed = 0
    for fn in files:
        path = os.path.join(QUEUE_DIR, fn)
        with open(path) as f:
            prop = json.load(f)
        src = prop.get("source_path")
        if not src or not os.path.exists(src):
            print(f"  ?  {prop['source_file']}: source PDF missing, skipped")
            continue
        text = extract_text(src)
        if not text:
            continue
        changed_names = False
        before = {k: prop["fields"].get(k) for k in ("date", "provider", "facility")}
        for key, fn_ in (("date", lambda t: extract_date(t, prop["source_file"])),
                         ("provider", extract_provider),
                         ("facility", extract_facility)):
            value, source = fn_(text)
            prop["fields"][key] = value
            prop["field_sources"][key] = source
        apply_roster(prop["fields"], prop["field_sources"], text,
                     prop["source_file"], ROSTER)
        for k in scrub_identifiers(prop["fields"], text, KNOWN_NAMES):
            src = prop["field_sources"].get(k) or "model"
            if "removed" not in src:
                prop["field_sources"][k] = src + ", patient name removed"
            changed_names = True
        after = {k: prop["fields"].get(k) for k in ("date", "provider", "facility")}
        if before != after or changed_names:
            changed += 1
            print(f"\n  {prop['source_file']}")
            for k in ("date", "provider", "facility"):
                if before[k] != after[k]:
                    print(f"      {k:<9} {before[k]!r}  ->  {after[k]!r}")
        with open(path, "w") as f:
            json.dump(prop, f, indent=2)
    print(f"\n{changed} of {len(files)} proposals changed.")


