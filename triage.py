# ============================================================
# Gate 1 - is this a clinical record at all?
# ============================================================
# Tuned against 69 real PDFs out of the Taildrop inbox, which is a much harder
# problem than it first looks. The folder holds journal articles about lupus,
# legal drafts, patient-education leaflets, this tracker's own PDF exports and
# work documents from the plant - all of them full of clinical vocabulary. A
# keyword score cannot separate those from actual records; on the first pass it
# passed 62 of 63, including a file containing nothing but an account recovery
# code.
#
# So the test is structural, not lexical. A record generated by a provider about
# a specific patient carries a demographics block (a name field plus a date of
# birth or MRN) or an encounter structure. A paper about anti-dsDNA isotypes
# carries neither, however much clinical language it contains.

MIN_CHARS = 400        # below this there is nothing to classify or describe

ANCHORS = {
    "patient_block": r"patient\s+name|patient\s*:|\bMRN\b|"
                     r"medical\s+record\s+(?:number|#)|patient\s+id|account\s*#",
    "dob_field":     r"\bDOB\b|date\s+of\s+birth",
    "encounter":     r"date\s+of\s+service|encounter\s+date|admission|discharge|"
                     r"visit\s+summary|chief\s+complaint|vitals?\b|"
                     r"collected\s+date|accession",
}

# (pattern, count at which the document is disqualified). Thresholds are set
# from the measured corpus: real records do touch these words, just rarely.
# Journal articles run 6-80 hits; a visit summary that happens to say
# "abstract" once does not.
VETOES = {
    "journal_article": (r"\bdoi\b|doi\.org|pubmed|\bet\s+al\.|\babstract\b|"
                        r"\bkeywords\b|\u00a9|\bvol\.\s*\d|peer.reviewed", 5),
    "own_report":      (r"biotracking|sardinetracker|flare\s+score|generated\s+by", 2),
    "legal_filing":    (r"\bplaintiff\b|\bdefendant\b|\bcomplaint\b|\bhereby\b|"
                        r"\bexhibit\b|\bC\.?F\.?R\.?\b|\baffidavit\b|"
                        r"\bcounsel\b|respectfully\s+submit", 5),
    "insurance_admin": (r"enrollment|premium|subscriber|member\s+id|deductible|"
                        r"policy\s+number|coverage", 10),
    "work_document":   (r"incident\s+number|work\s+order|site\s+name|"
                        r"down\s*(?:time|hrs)|equipment\s+status|\bMTSC\b", 2),
}


def classify(text):
    """Return (verdict, detail).

    clinical      - carries a demographics block or an encounter structure
    not_clinical  - tripped a veto, or carries no record structure at all
    ambiguous     - partial structure; described anyway, but flagged for a read
    too_short     - not enough text to judge
    """
    anchors = {k: len(re.findall(v, text, re.I | re.M))
               for k, v in ANCHORS.items()}
    vetoes = {k: len(re.findall(pat, text, re.I | re.M))
              for k, (pat, _) in VETOES.items()}
    tripped = [k for k, (_, limit) in VETOES.items() if vetoes[k] >= limit]

    detail = {"chars": len(text), "anchors": anchors, "vetoes": vetoes,
              "tripped": tripped}

    if len(text) < MIN_CHARS:
        detail["reason"] = f"only {len(text)} characters of text"
        return "too_short", detail

    if tripped:
        detail["reason"] = "looks like " + ", ".join(
            t.replace("_", " ") for t in tripped)
        return "not_clinical", detail

    identified = anchors["patient_block"] >= 1 and anchors["dob_field"] >= 1
    encounter = anchors["encounter"] >= 3
    if identified or encounter:
        detail["reason"] = ("patient demographics block" if identified
                            else "encounter structure")
        return "clinical", detail

    if anchors["patient_block"] or anchors["encounter"]:
        detail["reason"] = "partial record structure only"
        return "ambiguous", detail

    detail["reason"] = "no patient or encounter structure"
    return "not_clinical", detail


# ============================================================
# Gate 2 - deterministic fields
# ============================================================
# Anything readable off the page is read off the page; the model is only asked
# for what needs judgement. Every rule here was written against a real failure
# in the inbox, not imagined in advance.

DATE_RX = (r"(\d{1,2}/\d{1,2}/\d{4}|\d{4}-\d{2}-\d{2}"
           r"|[A-Z][a-z]{2,8}\s+\d{1,2},\s*\d{4}|\d{1,2}-[A-Z][a-z]{2}-\d{4})")

DATE_LABELS = [
    (10, r"collected\s*(?:date\s*/?\s*time)?"),
    (9,  r"date\s+of\s+service"),
    (8,  r"(?:service|visit|encounter|exam)\s+date"),
    (8,  r"visit\s+note\s*[-–]"),
    (7,  r"received\s*(?:date\s*/?\s*time)?"),
    (5,  r"(?:report|result)(?:ed)?\s+date"),
    (4,  r"electronically\s+signed\s+by"),
    (3,  r"date\s+printed"),
]

BIRTH_RX = re.compile(r"\bDOB\b|date\s+of\s+birth|birth\s*date", re.I)

# Nothing in this record predates the tracker's subject matter by decades. A
# date below this is a birthday, a form's printed example, or a copyright year.
EARLIEST_PLAUSIBLE = "2000-01-01"


def parse_date(raw):
    """Normalise one date string to YYYY-MM-DD, or None."""
    raw = raw.strip()
    for fmt in ("%m/%d/%Y", "%Y-%m-%d", "%B %d, %Y", "%b %d, %Y", "%d-%b-%Y"):
        try:
            return datetime.strptime(raw, fmt).date().isoformat()
        except ValueError:
            continue
    return None


def find_birth_dates(text):
    """Every date that looks like a date of birth, to be excluded everywhere.

    Two traps, both seen in this inbox:

    The label and its value are routinely on different lines - a visit note puts
    'DOB:' in a header row and '01/02/1980' in the row beneath. Looking only at
    the labelled line misses it, and the birthday then wins any 'earliest date'
    fallback.

    But that header row also reads 'Visit Note - March 4, 2026 ... DOB:',
    so blindly harvesting every date near the label blacklists the document's
    own date. Only dates *after* the label count, and the following lines are
    consulted only when the label's own line carries no date after it.
    """
    lines = text.splitlines()
    found = set()
    for i, line in enumerate(lines):
        m = BIRTH_RX.search(line)
        if not m:
            continue
        # Only the FIRST date after the label. A lab header reads
        # "DOB: 01/02/1980  Age: 36  Specimen: ...  Collected: 03/04/2026" -
        # taking every date after the label blacklists the collection date too,
        # and the document then has no date at all.
        after = line[m.end():]
        first = re.search(DATE_RX, after)
        if first:
            iso = parse_date(first.group(1))
            if iso:
                found.add(iso)
            continue
        for probe in lines[i + 1:i + 3]:      # value wrapped to the next row
            nxt = re.search(DATE_RX, probe)
            if nxt:
                iso = parse_date(nxt.group(1))
                if iso:
                    found.add(iso)
                break
    return found


FILENAME_DATE_PATTERNS = [
    # 2025.12.05 / 2026-01-20 / 2025_12_05
    (r"(20\d{2})[._-](\d{1,2})[._-](\d{1,2})", ("y", "m", "d")),
    # 04-01-2026 / 1.3.26 / 11_11_2025 / 9-2-2026
    (r"(\d{1,2})[._-](\d{1,2})[._-](20\d{2}|\d{2})", ("m", "d", "y")),
    # 20260219, no separators
    (r"(20\d{2})(\d{2})(\d{2})(?!\d)", ("y", "m", "d")),
    # 05112026 / 10012025, no separators
    (r"(?<!\d)(\d{2})(\d{2})(20\d{2})(?!\d)", ("m", "d", "y")),
]

# "Jan 15, 2026" / "Jan_15,_2026"
FILENAME_MONTH_RX = re.compile(
    r"([A-Z][a-z]{2,8})[_\s]+(\d{1,2}),?[_\s]*(20\d{2})")


def date_from_filename(name):
    """A date out of the filename. In this inbox that is the single most
    reliable signal available - the files are named by date of service."""
    stem = os.path.splitext(os.path.basename(name))[0]
    m = FILENAME_MONTH_RX.search(stem)
    if m:
        for fmt in ("%B %d %Y", "%b %d %Y"):
            try:
                return datetime.strptime(
                    f"{m.group(1)} {m.group(2)} {m.group(3)}", fmt).date().isoformat()
            except ValueError:
                continue
    for pattern, order in FILENAME_DATE_PATTERNS:
        for m in re.finditer(pattern, stem):
            parts = dict(zip(order, m.groups()))
            y, mo, d = parts["y"], int(parts["m"]), int(parts["d"])
            y = int(y) if len(y) == 4 else 2000 + int(y)
            if not (1 <= mo <= 12 and 1 <= d <= 31 and 2000 <= y <= 2099):
                continue
            try:
                return datetime(y, mo, d).date().isoformat()
            except ValueError:
                continue
    return None


def _date_appears_in(iso, text):
    """Does this date actually occur in the document, in any usual rendering?

    A filename is normally the best signal in this inbox, but not an infallible
    one: two copies of the same ER note arrived as ER-2025-03-04.pdf and
    2026-03-04-ER-pleurisy.pdf, with identical text whose own dates read
    03/4/2026. One filename is simply wrong by a year. When the filename's date
    is nowhere in the document, say so rather than filing it quietly.
    """
    d = datetime.strptime(iso, "%Y-%m-%d").date()
    renderings = {
        f"{d.month}/{d.day}/{d.year}", f"{d.month:02d}/{d.day:02d}/{d.year}",
        iso, d.strftime("%B %-d, %Y"), d.strftime("%b %-d, %Y"),
        d.strftime("%d-%b-%Y"),
    }
    return any(r in text for r in renderings)


def extract_date(text, filename=None):
    """Best document date. Labelled beats the filename; the filename beats a
    guess. There is deliberately no 'earliest date in the document' fallback -
    it was wrong far more often than it was right."""
    birthdays = find_birth_dates(text)
    today = datetime.now().date().isoformat()

    def usable(iso):
        return iso and iso not in birthdays and EARLIEST_PLAUSIBLE <= iso <= today

    best = None
    for line in text.splitlines():
        for weight, label in DATE_LABELS:
            m = re.search(label + r"\s*:?\s*" + DATE_RX, line, re.I)
            if m:
                iso = parse_date(m.group(1))
                if usable(iso) and (best is None or weight > best[0]):
                    best = (weight, iso, label)
    if best:
        return best[1], f"labelled date ({best[2]})"

    if filename:
        iso = date_from_filename(filename)
        if usable(iso):
            return iso, ("filename" if _date_appears_in(iso, text)
                         else "filename (NOT corroborated in the document)")

    return None, None


PROVIDER_LABELS = [
    r"electronically\s+signed\s+by", r"ordering\s+provider",
    r"attending(?:\s+physician)?", r"referring\s+(?:provider|physician)",
    r"\bprovider\b", r"physician",
]

CREDENTIAL_RX = re.compile(
    r"\b(?:M\.?D\.?|D\.?O\.?|N\.?P\.?|P\.?A\.?-?C?|R\.?N\.?|Ph\.?D\.?)\b")

# A clinician's name: capitalised words, nothing else. Written because matching
# "everything after the word 'provider'" harvested "Diagnosis", "Review",
# "| Legal Name: Firstname" and "for further fills if inhalers help".
NAME_RX = re.compile(
    r"^(?:Dr\.?\s+)?[A-Z][A-Za-z.'\-]*(?:\s+[A-Z][A-Za-z.'\-]*){0,3}"
    r"(?:,?\s*(?:M\.?D\.?|D\.?O\.?|N\.?P\.?|P\.?A\.?-?C|R\.?N\.?|Ph\.?D\.?))?$")


# Harvested from real documents: intake forms and portal exports put these
# immediately after a "Provider"/"Physician" label, and they read as names.
NOT_A_NAME = {
    "first name", "last name", "legal name", "full name", "middle name",
    "preferred name", "other health professional", "health professional",
    "primary care", "care team", "medical history", "chief complaint",
    "not available", "no provider", "unknown", "none", "self", "patient",
}


def _looks_like_a_name(val):
    if not (3 < len(val) < 45) or any(c in val for c in "|•❏:;/\\@"):
        return False
    if val.lower().strip(" .,") in NOT_A_NAME:
        return False
    if not NAME_RX.match(val):
        return False
    words = [w for w in re.split(r"[\s,]+", val) if w]
    if CREDENTIAL_RX.search(val):
        return True
    return len(words) >= 2          # "Diagnosis" and "Review" are not names


def extract_provider(text):
    """A clinician name from a labelled field. Returns None rather than a
    plausible-looking fragment - a wrong provider is worse than a blank one."""
    fallback = None
    for line in text.splitlines():
        for label in PROVIDER_LABELS:
            m = re.search(label + r"\s*:?\s{1,}(.+)", line, re.I)
            if not m:
                continue
            val = re.split(r"\s{3,}", m.group(1).strip())[0]
            val = re.sub(r",?\s*\d{1,2}[/-]\d{1,2}[/-]\d{2,4}.*$", "", val)
            val = val.strip(" .,:;-\t")
            if not _looks_like_a_name(val):
                continue
            if CREDENTIAL_RX.search(val):
                return val, f"labelled field ({label})"
            fallback = fallback or (val, f"labelled field ({label}), no credential")
    return fallback if fallback else (None, None)


# ============================================================
# Gate 2b - the clinician roster
# ============================================================
# The record already knows who these doctors are and where they work. Matching
# a known roster is deterministic and auditable, unlike asking a model to read a
# name off a letterhead - and clinic_name fills the facility field, which the
# letterhead heuristic almost never found.

ROSTER_CACHE = os.path.join(STATE_DIR, "clinicians.json")

# A clinician surname can also be an ordinary word
# ("standard of care", "standard precautions"). A bare surname is therefore only
# trusted when it is not a common word; otherwise the name must be anchored to
# a title or credentials.
# Fields naming someone other than the document's author.
REFERENCED_ROLE_RX = re.compile(
    r"(?:\bPCP\b|primary\s+care\s+(?:provider|physician)|"
    r"referring\s+(?:provider|physician|doctor)|"
    r"pharmac(?:y|ist)|emergency\s+contact|next\s+of\s+kin)"
    r"\s*:?[^|\n]{0,60}", re.I)

COMMON_WORDS = {
    "standard", "grant", "young", "field", "may", "chase", "cross", "king",
    "white", "brown", "green", "black", "long", "short", "best", "rich",
}


def fetch_roster(cfg, timeout=20):
    """GET the clinician roster from the server and cache it."""
    url = (cfg["server"].rstrip("/") + "/api/clinicians?user_id="
           + str(cfg["user_id"]))
    req = urllib.request.Request(
        url, headers={"Authorization": "Bearer " + cfg["api_token"]})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        data = json.loads(r.read())
    roster = data.get("clinicians") or []
    os.makedirs(STATE_DIR, exist_ok=True)
    with open(ROSTER_CACHE, "w") as f:
        json.dump(roster, f, indent=2)
    return roster


def load_roster():
    """The cached roster, or an empty list. Never fetches - matching must work
    with no network, and a stale roster is better than a failed run."""
    try:
        with open(ROSTER_CACHE) as f:
            return json.load(f)
    except (OSError, ValueError):
        return []


def _surname(name):
    parts = [w for w in re.split(r"[\s.]+", name or "") if w
             and w.lower().strip(".") not in ("dr", "mr", "ms", "mrs", "prof")]
    return parts[-1] if parts else None


def apply_roster(fields, sources, text, filename, roster):
    """Fill provider/facility from the clinician roster.

    A match on the *filename* wins outright: these files are named for the
    clinician seen, and the body of a cardiology note may well mention the
    primary care doctor - which is how Cardiology-2026-03-04.pdf came out
    attributed to Dr Example. Otherwise the roster only fills what the regexes
    left blank.
    """
    entry, why = match_clinician(text, filename, roster)
    if not entry:
        return
    authoritative = "surname in filename" in (why or "")
    if authoritative or not fields.get("provider"):
        fields["provider"] = entry["name"]
        sources["provider"] = why
    if entry.get("clinic_name") and (authoritative or not fields.get("facility")):
        fields["facility"] = entry["clinic_name"].strip()
        sources["facility"] = why


def match_clinician(text, filename, roster):
    """Best roster match for this document, or None.

    Position decides. A document's own clinician appears in the header, the
    letterhead or the signature block; a clinician merely *referenced* appears
    in the body ("follow up with Dr Example"). Matching anywhere in the document
    attributed both ER visits, the urgent care note and a nurse's telehealth
    visit to the primary care doctor, because each one says to follow up with
    him. So only the head, the signature block, and the filename count.
    """
    # Mercy's exports open with a patient banner:
    #   Name: ... | DOB: ... | MRN: ... | PCP: A. Physician, MD | ...
    # That is the patient's primary care doctor, not the author of the note, and
    # it appears on page one of every ER visit, urgent care note and telehealth
    # summary. Left in, it attributed all of them to the PCP. Referenced-role
    # fields are blanked before any matching happens.
    head = REFERENCED_ROLE_RX.sub(" ", text[:2000])
    tail = REFERENCED_ROLE_RX.sub(" ", text[-1200:])
    zones = head + "\n" + tail
    best = None
    for entry in roster:
        sur = _surname(entry.get("name"))
        if not sur or len(sur) < 3:
            continue
        e = re.escape(sur)
        score, why = 0, []
        if re.search(r"\b" + e + r"\b", filename, re.I):
            score += 6
            why.append("surname in filename")
        full = " ".join(w for w in (entry.get("name") or "").split()
                        if w.lower().strip(".") != "dr")
        if full and re.search(r"\b" + re.escape(full) + r"\b", zones, re.I):
            score += 5
            why.append("full name in header/signature")
        if re.search(r"\bDr\.?\s+" + e + r"\b", zones):
            score += 3
            why.append("'Dr <name>' in header/signature")
        if re.search(e + r"\s*,?\s*(?:M\.?D\.?|D\.?O\.?|N\.?P\.?|P\.?A\.?-?C|APRN)",
                     zones):
            score += 3
            why.append("credentials in header/signature")
        if sur.lower() not in COMMON_WORDS:
            n = len(re.findall(r"\b" + e + r"\b", head))
            if n:
                score += min(n, 2)
                why.append(f"surname in header x{n}")
        if score and (best is None or score > best[0]):
            best = (score, entry, why)
    if not best or best[0] < 5:
        return None, None
    return best[1], f"clinician roster ({', '.join(best[2])})"


ORG_RX = re.compile(
    r"(labor|patholog|clinic|hospital|health|medical|associates|diagnost|"
    r"dermatolog|rheumatolog|imaging|radiolog|cardiolog|neurolog|"
    r"center|centre|institute|group|physicians)", re.I)


NOT_A_FACILITY = re.compile(
    r"^(board\s+certified|medical\s+history|chief\s+complaint|"
    r"patient\s+information|date\s+of|page\s+\d)", re.I)


def _looks_like_an_org(line):
    if not (4 < len(line) < 70) or ":" in line or line.endswith("."):
        return False
    if NOT_A_FACILITY.match(line):
        return False
    if not line[0].isupper() or not ORG_RX.search(line):
        return False
    words = line.split()
    if len(words) < 2 or len(words) > 8:
        return False
    # A letterhead is Title Case or caps; a sentence is not.
    return sum(1 for w in words if w[:1].isupper()) >= len(words) - 1


def extract_facility(text):
    """The letterhead. On report PDFs the issuing lab or clinic is line one."""
    for line in text.splitlines()[:6]:
        line = " ".join(line.split())
        if _looks_like_an_org(line):
            return line, "letterhead (first lines)"
    for line in text.splitlines():
        m = re.search(r"performing\s+location\s*:?\s*(.+)", line, re.I)
        if m:
            val = " ".join(m.group(1).split())[:70]
            return val, "labelled field (performing location)"
    return None, None


